def run(paragraph, text, size=14, bold=False, italic=False):
    r = paragraph.add_run(text)
    r.font.name = "Times New Roman"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    r.font.size = Pt(size)
