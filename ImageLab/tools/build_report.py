def shade(cell, color):
    props = cell._element.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), color)
    props.append(shd)


def table(rows, widths):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.autofit = False
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    t._element.tblPr.append(layout)
    for index, width in enumerate(widths):
        t.columns[index].width = Emu(int(width * 635))
    props = t._element.tblPr
    borders = OxmlElement("w:tblBorders")
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        item = OxmlElement(f"w:{side}")
        item.set(qn("w:val"), "single")
        item.set(qn("w:sz"), "4")
        item.set(qn("w:color"), "000000")
        borders.append(item)
    props.append(borders)
    for r_index, row in enumerate(rows):
        for c_index, text in enumerate(row):
            cell = t.cell(r_index, c_index)
            cell.width = Emu(int(widths[c_index] * 635))
            p = cell.paragraphs[0]
            run(p, str(text), 11, r_index == 0)
            if r_index == 0:
                shade(cell, "E7ECF3")
    gap = doc.add_paragraph()
    gap.paragraph_format.space_after = Pt(4)


